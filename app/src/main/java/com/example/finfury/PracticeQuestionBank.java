    public static List<QuizManager.QuizQuestion> forSubject(String subject) {
        String s = subject == null ? "" : subject.toLowerCase(Locale.US);

        if (s.contains("chem") || s.contains("เคมี")) return chemistryQuestions();
        if (s.contains("phys") || s.contains("ฟิสิกส์")) return physicsQuestions();
        if (s.contains("program") || s.contains("โปรแกรม")) return programmingQuestions();
        if (s.contains("circuit") || s.contains("electric") || s.contains("วงจร")) return circuitQuestions();
        return calculusQuestions();
    }

    private static void add(List<QuizManager.QuizQuestion> list, String question, int correctIndex, String... options) {
        list.add(new QuizManager.QuizQuestion(question, options, correctIndex));
    }

