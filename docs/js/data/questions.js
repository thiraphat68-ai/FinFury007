/** Question set for a hero subject (QuestionBank.forSubject): accepts the English or Thai subject name. */
export function forSubject(subject) {
  const s = (subject || '').toLowerCase();
  if (s.includes('chem') || s.includes('เคมี')) return chemistryQuestions();
  if (s.includes('phys') || s.includes('ฟิสิกส์')) return physicsQuestions();
  if (s.includes('program') || s.includes('โปรแกรม')) return programmingQuestions();
  if (s.includes('circuit') || s.includes('electric') || s.includes('วงจร')) return circuitQuestions();
  return calculusQuestions();
}
